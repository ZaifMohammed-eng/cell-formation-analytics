"""Run the whole analysis: public data -> simulated line -> SQL KPIs -> triage ->
capacity -> economics -> change approval -> dashboard, report, metrics.json.

    python run_all.py            # about 30 s
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "src"))

from formation_analytics import capacity, change_approval, dashboard, economics, triage  # noqa: E402
from formation_analytics.config import CostConfig, LineConfig  # noqa: E402
from formation_analytics.lifetime import load_public, summarize  # noqa: E402
from formation_analytics.simulate import simulate, write_truth  # noqa: E402
from formation_analytics.warehouse import build, query  # noqa: E402


def _clean(o):
    if isinstance(o, dict):
        return {k: _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    if isinstance(o, (np.floating, float)):
        return round(float(o), 6)
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, np.bool_):
        return bool(o)
    return o


def main() -> dict:
    cfg, cost = LineConfig(), CostConfig()
    life = summarize(cost)
    models = life["screening_models_RT"]

    cells, retests, truth = simulate(cfg, life["distributions_RT"])
    write_truth(truth, ROOT / "data" / "ground_truth.json")
    con = build(cells, retests, cfg, ROOT / "data" / "formation.duckdb")

    kpi = query(con, "kpi_daily_yield")
    weekly = query(con, "throughput_weekly")
    pareto = query(con, "fail_pareto")
    (ROOT / "results").mkdir(exist_ok=True)
    kpi.to_csv(ROOT / "results" / "kpi_daily.csv", index=False)
    weekly.to_csv(ROOT / "results" / "throughput_weekly.csv", index=False)

    episodes = triage.run(con)
    scored = triage.score(episodes, truth)

    cap = capacity.summarize(cfg)
    ramps = {s: capacity.ramp(cfg, s) for s in ("baseline_only", "plan")}
    trade = economics.duration_tradeoff(con, models, cfg, cost)
    sweep = economics.limit_sweep(life["distributions_RT"]["baseline"], models["baseline"], cfg, cost)
    sweep.to_csv(ROOT / "results" / "rls_limit_sweep.csv", index=False)
    best_cell = sweep.loc[sweep.cost_cell_view.idxmin()]
    best_pack = sweep.loc[sweep.cost_pack_view.idxmin()]
    cur = sweep.loc[(sweep.rls_usl_mohm - cfg.rls_usl_mohm).abs().idxmin()]
    approval = change_approval.evaluate(con, cfg, life)

    totals = con.execute("SELECT COUNT(*), AVG(first_pass::INT), AVG(final_pass::INT) "
                         "FROM cell_disposition").fetchone()
    metrics = dict(
        public_data=life,
        line=dict(cells_simulated=int(totals[0]), days=cfg.n_days,
                  ramp_cells_per_day=[cfg.start_cells_per_day, cfg.end_cells_per_day],
                  first_pass_yield=totals[1], final_yield=totals[2],
                  fail_pareto=pareto.to_dict("records")),
        triage=dict(score=scored, episodes=[dict(
            mode=e.mode, days=[e.day_first, e.day_last], fail_rate=e.fail_rate,
            ref_rate=e.ref_rate, calc_mismatch_rate=e.calc_mismatch_rate,
            retest_pass_rate=e.retest_pass_rate, top_factor=e.top_factor,
            hot_levels=e.hot_levels, hot_share_of_fails=e.hot_share_of_fails,
            ml_importance=e.ml_importance, classification=e.classification) for e in episodes]),
        capacity=cap,
        duration_tradeoff=trade.reset_index().to_dict("records"),
        rls_limit=dict(current_usl=cfg.rls_usl_mohm,
                       current=cur.to_dict(), best_cell_view=best_cell.to_dict(),
                       best_pack_view=best_pack.to_dict()),
        change_approval=approval,
    )
    metrics = _clean(metrics)
    (ROOT / "results" / "metrics.json").write_text(json.dumps(metrics, indent=2))

    tiles = {
        "cells graded (simulated)": f"{totals[0]:,}",
        "first-pass yield": f"{totals[1]:.2%}",
        "final yield": f"{totals[2]:.2%}",
        "injected events classified correctly": f"{scored['n_correct']} / {scored['n_events']}",
        "false-alarm episodes": str(len(scored["false_alarm_episodes"])),
        "change approval": approval["decision"],
    }
    dashboard.build(ROOT / "dashboard" / "index.html", kpi, episodes, con, ramps, sweep,
                    cfg.rls_usl_mohm, load_public(), tiles)
    write_report(metrics, episodes)
    con.close()
    return metrics


def write_report(m: dict, episodes) -> None:
    pl, cap, ca = m["public_data"]["protocol_lifetime"], m["capacity"], m["change_approval"]
    t = {r["protocol"]: r for r in m["duration_tradeoff"]}
    s, lim = m["triage"]["score"], m["rls_limit"]
    sm = m["public_data"]["screening_models_RT"]
    pooled = m["public_data"]["rls_life_pooled"]["RT"]
    lines = [
        "# Formation report",
        "",
        "Generated by `run_all.py`. Line data are simulated, lifetime data are the public "
        "Weng et al. (2021) measurements; see README for which numbers are which.",
        "",
        "## Yield",
        f"- {m['line']['cells_simulated']:,} cells over {m['line']['days']} days, volume ramp "
        f"{m['line']['ramp_cells_per_day'][0]:,} to {m['line']['ramp_cells_per_day'][1]:,} cells/day.",
        f"- First-pass yield {m['line']['first_pass_yield']:.2%}, final yield after one retest "
        f"{m['line']['final_yield']:.2%}.",
        f"- Triage found {s['n_detected']} of {s['n_events']} injected events, classified "
        f"{s['n_correct']} correctly, with {len(s['false_alarm_episodes'])} false-alarm episode(s) "
        "(left as unresolved, not misclassified).",
        "",
        "## Preliminary root-cause notes",
        "",
    ]
    lines += [triage.rca_markdown(e) for e in episodes]
    lines += [
        "## Capacity and throughput",
        f"- Baseline (56 h) formation runs out of capacity on day "
        f"{cap['baseline_only']['first_day_over_capacity']} of the ramp; with no change, "
        f"backlog peaks at {cap['baseline_only']['peak_backlog_cells']:,.0f} cells and cycle time "
        f"reaches {cap['baseline_only']['cycle_time_end_h']:.0f} h.",
        f"- With the 14 h protocol the bottleneck moves to **{cap['plan']['bottleneck_at_end']}** at "
        f"{cap['plan']['util_at_end']:.0%} utilization and cycle time is "
        f"{cap['plan']['cycle_time_end_h']:.0f} h. Grading capacity is the next constraint.",
        f"- Formation channels needed for {m['line']['ramp_cells_per_day'][1]:,} cells/day at 85% "
        f"utilization: {cap['formation_channels_needed_at_end_volume']['baseline']:,} (baseline) vs "
        f"{cap['formation_channels_needed_at_end_volume']['fast']:,} (fast); installed "
        f"{cap['installed_formation_channels']:,}.",
        "",
        "## Formation duration vs COGS and warranty (assumed costs)",
        "| | baseline 56 h | fast 14 h |",
        "|---|---:|---:|",
        f"| formation cost per cell | ${t['baseline']['formation_cost']:.3f} | ${t['fast']['formation_cost']:.3f} |",
        f"| final yield (same build days) | {t['baseline']['final_yield']:.2%} | {t['fast']['final_yield']:.2%} |",
        f"| P(cell misses life spec) | {t['baseline']['warranty_claim_prob']:.1%} | {t['fast']['warranty_claim_prob']:.2%} |",
        f"| formation capex at end volume | ${t['baseline']['formation_capex_at_end_volume']/1e6:.1f} M | ${t['fast']['formation_capex_at_end_volume']/1e6:.1f} M |",
        "",
        f"Measured lifetime effect (public data): fast formation adds "
        f"{pl['RT']['gain_cycles']:.0f} cycles to 70% at room temperature (95% CI "
        f"{pl['RT']['gain_ci95'][0]:.0f}-{pl['RT']['gain_ci95'][1]:.0f}) and "
        f"{pl['45C']['gain_cycles']:.0f} at 45 C.",
        "",
        "## R_LS process limit",
        f"- Pooled across protocols, R_LS vs cycle life gives r = {pooled['pearson_r']:.2f} (RT), "
        "matching the paper. Within a protocol the link holds only for baseline cells "
        f"(r = {sm['baseline']['pearson_r']:.2f}, p = {sm['baseline']['p_value']:.3f}, n = "
        f"{sm['baseline']['n']}); for fast cells r = {sm['fast']['pearson_r']:.2f} "
        f"(p = {sm['fast']['p_value']:.2f}). The screen is only justified for baseline formation.",
        f"- At the current {lim['current_usl']:.0f} mOhm limit: R_LS yield "
        f"{lim['current']['yield_rls']:.1%}, P(cell misses spec) {lim['current']['cell_claim_prob']:.1%}, "
        f"P(96s4p pack misses spec) {lim['current']['pack_claim_prob']:.0%}.",
        f"- Scrap + warranty cost per good cell at {lim['current_usl']:.0f} mOhm: "
        f"${lim['current']['cost_cell_view']:.2f} (cell view), "
        f"${lim['current']['cost_pack_view']:.2f} (pack view). Cost-optimal limit: "
        f"{lim['best_cell_view']['rls_usl_mohm']:.1f} mOhm "
        f"(${lim['best_cell_view']['cost_cell_view']:.2f}) on cells, "
        f"{lim['best_pack_view']['rls_usl_mohm']:.1f} mOhm "
        f"(${lim['best_pack_view']['cost_pack_view']:.2f}) on packs. The weakest-link pack "
        "view makes a loose cell limit far more expensive than the cell view suggests.",
        "",
        "## Change approval: fast formation",
        f"- Decision: **{ca['decision']}** ({ca['n_pilot']:,} pilot cells vs "
        f"{ca['n_concurrent_baseline']:,} concurrent baseline cells).",
    ]
    lines += [f"- {k}: {'pass' if v else 'fail'}" for k, v in ca["checks"].items()]
    lines += ["", "Conditions:"] + [f"1. {c}" for c in ca["conditions"]]
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "reports" / "formation_report.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    m = main()
    s = m["triage"]["score"]
    print(f"cells: {m['line']['cells_simulated']:,}  triage: {s['n_correct']}/{s['n_events']} "
          f"correct, {len(s['false_alarm_episodes'])} false alarm(s)  approval: "
          f"{m['change_approval']['decision']}")
